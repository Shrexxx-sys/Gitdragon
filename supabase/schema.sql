-- Git Autopsy: Supabase schema (free tier).
-- Run once: Supabase dashboard -> SQL Editor -> paste this file -> Run.

-- Finished analyses. key = kind:target:intensity:marker (marker = repo pushed_at / profile updated_at),
-- so a repo that changes gets a new analysis, and repeated requests never call the AI again.
create table if not exists autopsy_cache (
  key         text primary key,
  kind        text not null,            -- 'repo' | 'profile'
  target      text not null,            -- 'owner/name' or 'username' (lowercase)
  intensity   text not null,            -- 'mild' | 'medium' | 'savage'
  marker      text not null,            -- last-updated marker from GitHub
  share_id    text not null unique,     -- used by /share/:id links
  data        jsonb not null,           -- the analysis (public GitHub data only)
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null
);
create index if not exists autopsy_cache_target_idx on autopsy_cache (kind, target);
create index if not exists autopsy_cache_expires_idx on autopsy_cache (expires_at);

-- Daily usage per anonymous install. install_hash is a salted SHA-256 of a random ID
-- generated by the extension: it can't be traced back to a person.
create table if not exists usage_daily (
  install_hash text not null,
  day          date not null,
  count        integer not null default 0,
  primary key (install_hash, day)
);

-- Atomic "+1 and tell me the new count" (safe when two requests arrive at the same time).
create or replace function increment_usage(p_install text, p_day date)
returns integer
language sql
as $$
  insert into usage_daily (install_hash, day, count)
  values (p_install, p_day, 1)
  on conflict (install_hash, day) do update set count = usage_daily.count + 1
  returning count;
$$;

-- Lock everything down: no public access at all. Only the server (service role key) can use these.
alter table autopsy_cache enable row level security;
alter table usage_daily enable row level security;
revoke all on autopsy_cache, usage_daily from anon, authenticated;
revoke execute on function increment_usage(text, date) from anon, authenticated, public;

